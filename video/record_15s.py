"""Record the screen takes for the 15-second silent Iris clip (video/shotlist-15s.md).

Launches ``python gui.py --demo``, drives one full demo session over its
localhost control port, and records four short takes with ffmpeg (gdigrab,
1920x1080, 30 fps, mouse hidden) into video/build/raw15/. Every click is
automated. Nothing is recorded while the app is loading or waiting, so the
edit only needs to trim each take's lead-in.

Takes (each recorded with some slack; edit_15s.py picks the exact frames):
  devices     Experiment tab: devices unchecked, then Calibrate Devices
              turns all six rows green                       -> shots 1 and 3a
  checklist   Warmup checklist ticked fast, Continue unlocks -> shot 2
  rec         Performance phase starts: REC + timer          -> shot 3b
The session folder / sync_manifest.json shot and the results screen are
generated by the edit from the finished demo session, so nothing else is
recorded. A --dry-run never writes or deletes any take.

ffmpeg records the whole desktop. Iris is kept on top and the script stops
(deleting the take) if any other window is visible. Still, turn on Do Not
Disturb, close anything private and leave the PC alone until it finishes
(about 2 minutes).

Usage (from the repo root, in the Python environment Iris runs in):

    python video/record_15s.py            # record all four takes
    python video/record_15s.py --dry-run  # drive the app without recording
"""

import argparse
import ctypes
import json
import socket
import subprocess
import sys
import tempfile
import time
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
RAW_DIR = REPO / "video" / "build" / "raw15"
TAKES_JSON = RAW_DIR / "takes.json"
CLIPS_DIR = REPO / "demo_output" / "clips"

LEAD = 1.0    # seconds recorded before each take's actions start
EXTRA = 1.5   # seconds recorded after each take, as slack for the edit

# Seconds of action to capture per take (LEAD is added before and EXTRA after)
LENGTHS = {
    "checklist": 4.5,
    "devices": 3.0,
    "rec": 4.0,
}


class App:
    """Client for the demo control server (see src/demo.py)."""

    def __init__(self, port):
        self.port = port

    def send(self, cmd, **kw):
        payload = dict(cmd=cmd, **kw)
        with socket.create_connection(("127.0.0.1", self.port), timeout=15) as sock:
            sock.sendall((json.dumps(payload) + "\n").encode())
            data = b""
            while not data.endswith(b"\n"):
                chunk = sock.recv(65536)
                if not chunk:
                    break
                data += chunk
        reply = json.loads(data)
        if not reply.get("ok"):
            raise RuntimeError(f"{cmd}: {reply.get('error')}")
        return reply.get("result")

    def state(self):
        return self.send("state")

    def wait(self, what, pred, timeout=60):
        deadline = time.time() + timeout
        while time.time() < deadline:
            st = self.state()
            if pred(st):
                return st
            time.sleep(0.2)
        raise TimeoutError(f"timed out waiting for {what}; last state: {st}")


class Recorder:
    def __init__(self, app, args, screen):
        self.app = app
        self.args = args
        self.screen = screen  # physical desktop size (w, h)
        self.takes = json.loads(TAKES_JSON.read_text()) if TAKES_JSON.exists() else {}

    def planned(self, take):
        return LENGTHS[take]

    def record(self, take, actions=(), widgets=(), keep_on_top=True):
        """Record one take. actions: [(seconds after take start, callable)]."""
        if self.args.only and take not in self.args.only:
            for _, fn in sorted(actions, key=lambda a: a[0]):
                fn()
            return
        if keep_on_top:
            # Make sure only Iris is on screen before anything is captured
            self.app.send("window", topmost=True)
            time.sleep(0.4)
            require_iris_in_front(take)
        length = LEAD + self.planned(take) + EXTRA
        out = RAW_DIR / f"{take}.mp4"
        print(f"  [rec] {take}: recording {length:.1f}s")
        proc = None
        if not self.args.dry_run:
            proc = subprocess.Popen(self._ffmpeg_cmd(out, length), stdin=subprocess.DEVNULL)
        t0 = time.perf_counter() + LEAD
        for at, fn in sorted(actions, key=lambda a: a[0]):
            time.sleep(max(0.0, t0 + at - time.perf_counter()))
            fn()
        geometry = self.app.send("geometry", widgets=list(widgets)) if widgets else {}
        time.sleep(max(0.0, t0 - LEAD + length - time.perf_counter()))
        if proc:
            if proc.wait(timeout=30) != 0:
                raise RuntimeError(f"ffmpeg failed while recording {take}")
        if keep_on_top:
            # In a dry run nothing was recorded, so never delete an existing take
            require_iris_in_front(take, delete=None if self.args.dry_run else out)
        if self.args.dry_run:
            return
        w, h = self.screen
        self.takes[take] = {
            "file": out.name,
            "lead": LEAD - self.args.startup,
            "length": length,
            "screen": [w, h],
            # widget rectangles as fractions of the screen: [x, y, w, h]
            "widgets": {k: (None if r is None else [r[0] / w, r[1] / h, r[2] / w, r[3] / h])
                        for k, r in geometry.items()},
        }
        TAKES_JSON.write_text(json.dumps(self.takes, indent=2))

    def _ffmpeg_cmd(self, out, length):
        cmd = ["ffmpeg", "-y", "-hide_banner", "-loglevel", "error",
               "-f", "gdigrab", "-framerate", "30", "-draw_mouse", "0", "-i", "desktop"]
        if self.args.audio:
            cmd += ["-f", "dshow", "-i", f"audio={self.args.audio}"]
        cmd += ["-t", f"{length:.2f}",
                "-vf", "scale=1920:1080:force_original_aspect_ratio=decrease,"
                       "pad=1920:1080:(ow-iw)/2:(oh-ih)/2:color=0x0E0E2C,fps=30,format=yuv420p",
                "-c:v", "libx264", "-preset", "ultrafast", "-crf", "16"]
        if self.args.audio:
            cmd += ["-c:a", "aac", "-b:a", "192k"]
        return cmd + [str(out)]


class _Point(ctypes.Structure):
    _fields_ = [("x", ctypes.c_long), ("y", ctypes.c_long)]


def visible_titles():
    """Titles of the top-level windows visible at the centre and near each corner."""
    user32 = ctypes.windll.user32
    user32.WindowFromPoint.argtypes = [_Point]
    user32.WindowFromPoint.restype = ctypes.c_void_p
    user32.GetAncestor.argtypes = [ctypes.c_void_p, ctypes.c_uint]
    user32.GetAncestor.restype = ctypes.c_void_p
    user32.GetWindowTextW.argtypes = [ctypes.c_void_p, ctypes.c_wchar_p, ctypes.c_int]
    w, h = user32.GetSystemMetrics(0), user32.GetSystemMetrics(1)
    titles = set()
    for fx, fy in [(0.5, 0.5), (0.03, 0.03), (0.97, 0.03), (0.03, 0.97), (0.97, 0.97)]:
        hwnd = user32.WindowFromPoint(_Point(int(w * fx), int(h * fy)))
        root = user32.GetAncestor(hwnd, 2)  # GA_ROOT
        buf = ctypes.create_unicode_buffer(512)
        user32.GetWindowTextW(root, buf, 512)
        titles.add(buf.value)
    return titles


def require_iris_in_front(take, delete=None):
    """Stop if anything but Iris is visible, so nothing private ends up in a take."""
    others = {t for t in visible_titles() if not t.startswith("Iris")}
    if not others:
        return
    if delete is not None and delete.exists():
        delete.unlink()
    raise RuntimeError(f"{sorted(others)} was visible over Iris during take '{take}'. "
                       "The take was discarded; close other windows and run again.")


def screen_size():
    try:
        ctypes.windll.user32.SetProcessDPIAware()
    except AttributeError:
        pass
    user32 = ctypes.windll.user32
    return user32.GetSystemMetrics(0), user32.GetSystemMetrics(1)


def check_capture(screen):
    """Grab one frame and make sure gdigrab sees the whole desktop."""
    with tempfile.TemporaryDirectory() as tmp:
        png = Path(tmp) / "probe.png"
        subprocess.run(["ffmpeg", "-y", "-hide_banner", "-loglevel", "error", "-f", "gdigrab",
                        "-i", "desktop", "-frames:v", "1", str(png)], check=True)
        out = subprocess.run(["ffprobe", "-v", "error", "-select_streams", "v:0", "-show_entries",
                              "stream=width,height", "-of", "csv=p=0", str(png)],
                             capture_output=True, text=True, check=True).stdout.strip()
    grabbed = tuple(int(v) for v in out.split(","))
    print(f"Screen {screen[0]}x{screen[1]}, ffmpeg captures {grabbed[0]}x{grabbed[1]}")
    if grabbed != tuple(screen):
        print("WARNING: ffmpeg is not capturing the full screen. Set Windows display scaling to "
              "100% (Settings > System > Display) and run again.")
        return False
    if abs(screen[0] / screen[1] - 16 / 9) > 0.01:
        print("NOTE: the screen is not 16:9, so recordings will be letterboxed. "
              "A 1920x1080 display gives the cleanest result.")
    return True


def run_session(app, rec):
    app.wait("the GUI", lambda s: s is not None, timeout=60)
    app.send("window", topmost=True)
    time.sleep(2.0)  # let the full-screen window settle
    app.send("console", show=False)

    # --- Shots 1 and 3a: Experiment tab, before and during the device check ---
    app.send("tab", name="Experiment")
    time.sleep(0.8)
    rec.record("devices", actions=[(0.2, lambda: app.send("calibrate"))],
               widgets=["device_status"])
    app.wait("calibration", lambda s: s["calibration_done"] and not s["running"], timeout=30)
    time.sleep(0.5)

    # --- Phases 1-3 (not recorded: loading and camera roles) ---
    app.send("run")
    app.wait("camera previews", lambda s: s["camera_selection"], timeout=90)
    time.sleep(0.8)
    app.send("select_roles", overhead="overhead_camera")
    app.wait("warmup checklist", lambda s: s["phase_id"] == "warmup_calibration"
             and s["continue_visible"], timeout=60)
    time.sleep(0.8)

    # --- Shot 2: tick every box quickly so the whole checklist fits in ~4 s ---
    n_items = app.state()["checklist_len"]
    step = min(0.35, 3.2 / max(n_items, 1))
    rec.record("checklist", widgets=["checklist", "continue"], actions=[
        (0.3 + step * i, lambda i=i: app.send("tick", index=i)) for i in range(n_items)
    ])
    app.send("continue")   # T-pose done
    app.wait("clap prompt", lambda s: s["continue_visible"], timeout=20)
    time.sleep(1.0)

    # --- Shot 3b: the last Continue starts the Performance recording ---
    rec.record("rec", actions=[(0.3, lambda: app.send("continue"))],
               widgets=["phase_name", "rec"])
    app.wait("performance recording", lambda s: s["phase_id"] == "performance"
             and s["recording"], timeout=30)

    # --- Rest of the session, unrecorded, so the folder for shot 4 is complete ---
    time.sleep(6.0)
    app.send("tick")
    app.send("continue")
    for phase in ("review", "scoring"):
        app.wait(f"{phase} player", lambda s, p=phase: s["phase_id"] == p and s["video_player"],
                 timeout=30)
        time.sleep(1.0)
        app.send("playpause")  # Start: 3-2-1 countdown, then playback
        app.wait(f"{phase} playback", lambda s: s["video_playing"] and not s["countdown"],
                 timeout=15)
        time.sleep(1.0)
        if app.state()["phase_id"] == phase:
            app.send("continue")
    app.wait("finish checklist", lambda s: s["phase_id"] == "finish" and s["continue_visible"],
             timeout=30)
    time.sleep(0.8)
    app.send("tick")
    app.send("continue")
    print("  Post-processing the demo session...")
    st = app.wait("post-processing", lambda s: not s["running"], timeout=600)
    print(f"  Demo session: {st['session_dir']}")
    return st["session_dir"]


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--port", type=int, default=47900)
    parser.add_argument("--dry-run", action="store_true", help="drive the app without recording")
    parser.add_argument("--startup", type=float, default=0.3,
                        help="ffmpeg start-up delay to allow for when trimming (default 0.3 s)")
    args = parser.parse_args()
    args.only = None
    args.audio = None   # silent clip

    RAW_DIR.mkdir(parents=True, exist_ok=True)

    screen = screen_size()
    if not args.dry_run and not check_capture(screen):
        sys.exit(1)
    for role in ("overhead", "face"):
        clip = CLIPS_DIR / f"{role}.mp4"
        print(f"{role} camera: {'test clip ' + str(clip) if clip.exists() else 'synthetic pattern'}")

    gui = subprocess.Popen([sys.executable, str(REPO / "gui.py"), "--demo",
                            "--demo-port", str(args.port)], cwd=REPO)
    app = App(args.port)
    rec = Recorder(app, args, screen)
    try:
        deadline = time.time() + 60
        while True:
            try:
                app.state()
                break
            except OSError:
                if gui.poll() is not None or time.time() > deadline:
                    raise RuntimeError("the demo GUI did not start")
                time.sleep(0.5)
        session = run_session(app, rec)
        (RAW_DIR / "session.txt").write_text(session)
        print(f"\nDone. Takes are in {RAW_DIR}")
    finally:
        try:
            app.send("quit")
        except Exception:
            pass
        try:
            gui.wait(timeout=10)
        except subprocess.TimeoutExpired:
            gui.kill()


if __name__ == "__main__":
    main()
